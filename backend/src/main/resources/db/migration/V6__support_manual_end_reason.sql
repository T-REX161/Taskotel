-- V6: support for the "End Support" action on support_assignments.
--
-- Two changes to one table; no row is updated or deleted and no column is added, so every existing row stays valid:
--   1. The end-reason CHECK constraint also allows 'MANUALLY_ENDED' (same list plus the new value).
--   2. "One support record per task, ever" (UNIQUE task_id) becomes "one ACTIVE support record per task" (partial unique
--      index). Without this, a task whose support was ended could never be supported again, because its ended record
--      stays in the history.
--
-- The CHECK constraint has one of two names depending on how the table was created: ck_support_assignments_end_reason
-- (Flyway V5) or support_assignments_end_reason_check (generated by Hibernate ddl-auto=update on a development
-- database). Whichever exists is replaced; the result always carries the Flyway name.
--
-- Run by hand in one transaction:  psql -1 -v ON_ERROR_STOP=1 -f V6__support_manual_end_reason.sql
--
-- Rollback (only valid while no row uses MANUALLY_ENDED and no task has two support records):
--   DROP INDEX uk_support_assignments_active_task;
--   ALTER TABLE support_assignments ADD CONSTRAINT uk_support_assignments_task UNIQUE (task_id);
--   ALTER TABLE support_assignments DROP CONSTRAINT ck_support_assignments_end_reason;
--   ALTER TABLE support_assignments ADD CONSTRAINT ck_support_assignments_end_reason CHECK (end_reason IS NULL OR end_reason IN
--       ('TASK_COMPLETED', 'TASK_CANCELLED', 'TASK_DELETED', 'TASK_REASSIGNED', 'TASK_MOVED'));

SET LOCAL lock_timeout = '5s';

DO $$
BEGIN
    IF to_regclass(format('%I.support_assignments', current_schema())) IS NULL THEN
        RAISE EXCEPTION 'V6: %.support_assignments does not exist. Apply V5 first. No changes were made.', current_schema();
    END IF;
END
$$;

ALTER TABLE support_assignments DROP CONSTRAINT IF EXISTS ck_support_assignments_end_reason;
ALTER TABLE support_assignments DROP CONSTRAINT IF EXISTS support_assignments_end_reason_check;

ALTER TABLE support_assignments ADD CONSTRAINT ck_support_assignments_end_reason CHECK (end_reason IS NULL OR end_reason IN
    ('TASK_COMPLETED', 'TASK_CANCELLED', 'TASK_DELETED', 'TASK_REASSIGNED', 'TASK_MOVED', 'MANUALLY_ENDED'));

-- Created before the old constraint is dropped, so a task is never left without a guard
CREATE UNIQUE INDEX IF NOT EXISTS uk_support_assignments_active_task ON support_assignments (task_id) WHERE status = 'ACTIVE';
ALTER TABLE support_assignments DROP CONSTRAINT IF EXISTS uk_support_assignments_task;
